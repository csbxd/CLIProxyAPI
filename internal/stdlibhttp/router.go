var _ IRouter = (*Engine)(nil)

// New returns a new blank Engine.
func New() *Engine {
	engine := &Engine{
		RouterGroup: RouterGroup{
			basePath: "/",
			root:     true,
		},
		RedirectTrailingSlash:  true,
		RedirectFixedPath:      false,
		HandleMethodNotAllowed: false,
		ForwardedByClientIP:    true,
		RemoteIPHeaders:        []string{"X-Forwarded-For", "X-Real-IP"},
		UseRawPath:             false,
		UnescapePathValues:     true,
		MaxMultipartMemory:     defaultMultipartMemory,
		trees:                  make(methodTrees, 0, 9),
		trustedCIDRs:           defaultTrustedCIDRs,
	}
	engine.engine = engine
	engine.rebuild404Handlers()
	engine.rebuild405Handlers()
	return engine
}

// Default returns a new Engine. Middleware is installed by the application.
func Default() *Engine { return New() }

// Handler returns the Engine as an http.Handler.
func (engine *Engine) Handler() http.Handler { return engine }

// ServeHTTPHandler returns the Engine as an http.Handler.
func (engine *Engine) ServeHTTPHandler() http.Handler { return engine }

// ServeHTTP conforms to http.Handler.
func (engine *Engine) ServeHTTP(w http.ResponseWriter, req *http.Request) {
	params := make(Params, 0, engine.maxParams)
	skipped := make([]skippedNode, 0, engine.maxSections)
	c := &Context{
		Request:      req,
		Writer:       newResponseWriter(w),
		engine:       engine,
		index:        -1,
		params:       &params,
		skippedNodes: &skipped,
	}
	engine.handleHTTPRequest(c)
}

// HandleContext re-enters a context after its request has been rewritten.
func (engine *Engine) HandleContext(c *Context) {
	oldIndexValue := c.index
	oldHandlers := c.handlers
	engine.resetContext(c)
	engine.handleHTTPRequest(c)
	c.index = oldIndexValue
	c.handlers = oldHandlers
}

func (engine *Engine) resetContext(c *Context) {
	c.Params = c.Params[:0]
	c.Errors = c.Errors[:0]
	c.handlers = nil
	c.fullPath = ""
	c.index = -1
	if c.params == nil {
		p := make(Params, 0, engine.maxParams)
		c.params = &p
	} else {
		*c.params = (*c.params)[:0]
	}
	if c.skippedNodes == nil {
		s := make([]skippedNode, 0, engine.maxSections)
		c.skippedNodes = &s
	} else {
		*c.skippedNodes = (*c.skippedNodes)[:0]
	}
}

func (engine *Engine) handleHTTPRequest(c *Context) {
	httpMethod := c.Request.Method
	rPath := c.Request.URL.Path
	unescape := false
	if engine.UseRawPath && len(c.Request.URL.RawPath) > 0 {
		rPath = c.Request.URL.RawPath
		unescape = engine.UnescapePathValues
	}
	if engine.RemoveExtraSlash {
		rPath = cleanPath(rPath)
	}

	for i, tl := 0, len(engine.trees); i < tl; i++ {
		if engine.trees[i].method != httpMethod {
			continue
		}
		root := engine.trees[i].root
		value := root.getValue(rPath, c.params, c.skippedNodes, unescape)
		if value.params != nil {
			c.Params = *value.params
		}
		if value.handlers != nil {
			c.handlers = value.handlers
			c.fullPath = value.fullPath
			c.Next()
			c.Writer.WriteHeaderNow()
			return
		}
		if httpMethod != http.MethodConnect && rPath != "/" {
			if value.tsr && engine.RedirectTrailingSlash {
				redirectTrailingSlash(c)
				return
			}
			if engine.RedirectFixedPath && redirectFixedPath(c, root, engine.RedirectFixedPath) {
				return
			}
		}
		break
	}

	if engine.HandleMethodNotAllowed && len(engine.trees) > 0 {
		allowed := make([]string, 0, len(engine.trees)-1)
		for _, tree := range engine.trees {
			if tree.method == httpMethod {
				continue
			}
			if value := tree.root.getValue(rPath, nil, c.skippedNodes, unescape); value.handlers != nil {
				allowed = append(allowed, tree.method)
			}
		}
		if len(allowed) > 0 {
			c.handlers = engine.allNoMethod
			c.Writer.Header().Set("Allow", strings.Join(allowed, ", "))
			serveError(c, http.StatusMethodNotAllowed, default405Body)
			return
		}
	}

	c.handlers = engine.allNoRoute
	serveError(c, http.StatusNotFound, default404Body)
}

func (engine *Engine) addRoute(method, routePath string, handlers HandlersChain) {
	assert1(routePath != "" && routePath[0] == '/', "path must begin with '/'")
	assert1(method != "", "HTTP method can not be empty")
	assert1(len(handlers) > 0, "there must be at least one handler")

	root := engine.trees.get(method)
	if root == nil {
		root = new(node)
		root.fullPath = "/"
		engine.trees = append(engine.trees, methodTree{method: method, root: root})
	}
	root.addRoute(routePath, handlers)
	if paramsCount := countParams(routePath); paramsCount > engine.maxParams {
		engine.maxParams = paramsCount
	}
	if sectionsCount := countSections(routePath); sectionsCount > engine.maxSections {
		engine.maxSections = sectionsCount
	}
}

// Routes returns all registered routes.
func (engine *Engine) Routes() (routes RoutesInfo) {
	for _, tree := range engine.trees {
		routes = iterate("", tree.method, routes, tree.root)
	}
	return routes
}

func iterate(routePath, method string, routes RoutesInfo, root *node) RoutesInfo {
	routePath += root.path
	if len(root.handlers) > 0 {
		handler := root.handlers.Last()
		routes = append(routes, RouteInfo{
			Method: method, Path: routePath, Handler: nameOfFunction(handler), HandlerFunc: handler,
		})
	}
	for _, child := range root.children {
		routes = iterate(routePath, method, routes, child)
	}
	return routes
}

func (engine *Engine) NoRoute(handlers ...HandlerFunc) {
	engine.noRoute = handlers
	engine.rebuild404Handlers()
}

func (engine *Engine) NoMethod(handlers ...HandlerFunc) {
	engine.noMethod = handlers
	engine.rebuild405Handlers()
}

func (engine *Engine) Use(middleware ...HandlerFunc) IRoutes {
	engine.RouterGroup.Use(middleware...)
	engine.rebuild404Handlers()
	engine.rebuild405Handlers()
	return engine
}

func (engine *Engine) rebuild404Handlers() {
	engine.allNoRoute = engine.combineHandlers(engine.noRoute)
}

func (engine *Engine) rebuild405Handlers() {
	engine.allNoMethod = engine.combineHandlers(engine.noMethod)
}

// SetTrustedProxies validates and stores proxy CIDRs for compatibility with Gin's API.
func (engine *Engine) SetTrustedProxies(trustedProxies []string) error {
	engine.trustedCIDRs = nil
	for _, trustedProxy := range trustedProxies {
		if !strings.Contains(trustedProxy, "/") {
			ip := parseIP(trustedProxy)
			if ip == nil {
				return &net.ParseError{Type: "IP address", Text: trustedProxy}
			}
			if len(ip) == net.IPv4len {
				trustedProxy += "/32"
			} else if len(ip) == net.IPv6len {
				trustedProxy += "/128"
			}
		}
		_, cidr, err := net.ParseCIDR(trustedProxy)
		if err != nil {
			return err
		}
		engine.trustedCIDRs = append(engine.trustedCIDRs, cidr)
	}
	return nil
}

func parseIP(value string) net.IP {
	parsed := net.ParseIP(value)
	if ipv4 := parsed.To4(); ipv4 != nil {
		return ipv4
	}
	return parsed
}

func (engine *Engine) isTrustedProxy(ip net.IP) bool {
	for _, cidr := range engine.trustedCIDRs {
		if cidr.Contains(ip) {
			return true
		}
	}
	return false
}

func serveError(c *Context, code int, defaultMessage []byte) {
	setPendingStatus(c.Writer, code)
	c.Next()
	if c.Writer.Written() {
		return
	}
	if c.Writer.Status() == code {
		c.Writer.Header().Set("Content-Type", "text/plain; charset=utf-8")
		_, _ = c.Writer.Write(defaultMessage)
		return
	}
	c.Writer.WriteHeaderNow()
}

func setPendingStatus(writer ResponseWriter, status int) {
	if wrapped, ok := writer.(*responseWriter); ok {
		if !wrapped.written {
			wrapped.status = status
		}
		return
	}
	writer.WriteHeader(status)
}

func redirectTrailingSlash(c *Context) {
	req := c.Request
	p := req.URL.Path
	if prefix := path.Clean(req.Header.Get("X-Forwarded-Prefix")); prefix != "." {
		prefix = regSafePrefix.ReplaceAllString(prefix, "")
		prefix = regRemoveRepeatedChar.ReplaceAllString(prefix, "/")
		p = prefix + "/" + req.URL.Path
	}
	req.URL.Path = p + "/"
	if length := len(p); length > 1 && p[length-1] == '/' {
		req.URL.Path = p[:length-1]
	}
	redirectRequest(c)
}

func redirectFixedPath(c *Context, root *node, trailingSlash bool) bool {
	if fixedPath, ok := root.findCaseInsensitivePath(cleanPath(c.Request.URL.Path), trailingSlash); ok {
		c.Request.URL.Path = string(fixedPath)
		redirectRequest(c)
		return true
	}
	return false
}

func redirectRequest(c *Context) {
	req := c.Request
	rURL := req.URL.String()
	code := http.StatusMovedPermanently
	if req.Method != http.MethodGet {
		code = http.StatusTemporaryRedirect
	}
	http.Redirect(c.Writer, req, rURL, code)
	c.Writer.WriteHeaderNow()
}

// CreateTestContext creates a context backed by the supplied writer.
